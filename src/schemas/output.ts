/**
 * Output schema publication (P9): per-platform JSON Schema documents.
 *
 * For every output format, `toki schema` publishes a draft-07 JSON Schema that
 * describes the *JSON view* of that platform's generated artifacts for the
 * given token set:
 *
 * - **css / tailwind** — the custom-property map: `{ "--color-primary": ... }`
 * - **js / angular / angular-11 / svelte / vue** — the named-export object:
 *   `{ "colorPrimary": ... }` (CONSTANT_CASE for Angular)
 * - **react-native / react** — the grouped category object:
 *   `{ "colors": { "primary": ... } }`
 * - **stencil** — camelCase exports plus the grouped `tokens` object
 *
 * Schemas are generated from the *resolved* tokens (platform transforms
 * applied, mirroring what each generator sees), list every emitted key in
 * `properties` with `additionalProperties: false`, and can be associated with
 * JSON documents in editors (e.g. VS Code `json.schemas`) for autocomplete
 * and validation.
 */

